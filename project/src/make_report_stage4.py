# -*- coding: utf-8 -*-
"""Генерация отчёта 4 этапа (.docx): исследование параметров системы."""
import argparse
import json
from pathlib import Path

from docx_helpers import new_report, header_block, h2, h3, p, bullets, table, picture

ROOT = Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--m960", required=True, help="путь к val_metrics.json модели 960")
    ap.add_argument("--status960", required=True, help="путь к оценке статусов модели 960")
    args = ap.parse_args()

    m640 = json.load(open(ROOT / "runs" / "detect" / "runs" / "detect_n_640" / "val_metrics.json", encoding="utf-8"))
    m960 = json.load(open(args.m960, encoding="utf-8"))
    s640 = json.load(open(ROOT / "runs" / "status_eval_best.json", encoding="utf-8"))
    s960 = json.load(open(args.status960, encoding="utf-8"))

    doc = new_report()
    header_block(doc, 4, "Nov 23, 2026")

    h2(doc, "1. План исследования")
    p(doc,
      "На 3 этапе система достигла точности статуса 0.910 и полноты скрытых нарушений "
      "1.0 на тестовом наборе (47 изображений, 155 рабочих). Цель 4 этапа — понять, "
      "как параметры влияют на качество, и найти, что можно улучшить. Исследуются "
      "пять групп параметров: порог уверенности детектора (conf_det), порог привязки "
      "каски к голове (thr_head), пороги привязки к рукам и поясу (thr_hand, thr_belt), "
      "порог уверенности ключевых точек позы (kp_conf) и резервная оценка положения "
      "головы по плечам для рабочих спиной (head_fallback). Отдельно сравниваются два "
      "размера входа детектора: 640×640 и 960×960. Метрики: точность статуса и полнота "
      "скрытых нарушений на тестовом наборе, для детектора — AP по классам на "
      "валидационной выборке.")
    p(doc,
      "Базовая конфигурация: conf_det = 0.25, thr_head = 0.15, thr_hand = thr_belt = 0.35, "
      "kp_conf = 0.5, head_fallback выключен, размер входа 640. В каждой серии меняется "
      "один параметр, остальные фиксированы.")

    h2(doc, "2. Влияние порогов алгоритма")
    h3(doc, "2.1. Порог уверенности детектора")
    table(doc,
          ["conf_det", "0.15", "0.25", "0.40", "0.60"],
          [["Точность статуса", "0.910", "0.910", "0.916", "0.916"],
           ["Полнота скрытых нарушений", "1.0", "1.0", "0.0", "0.0"]])
    p(doc,
      "Повышение порога с 0.25 до 0.40 немного поднимает точность статуса (меньше "
      "ложных срабатываний детектора на посторонние объекты), но полнота скрытых "
      "нарушений падает до нуля: каска в руках — нетипичное положение, и детектор "
      "находит её с уверенностью ниже 0.4. Это ключевой компромисс: высокий порог "
      "уверенности «срезает» именно те нарушения, ради которых строится система. "
      "Выбран порог 0.25.")

    h3(doc, "2.2. Порог привязки каски к голове")
    table(doc,
          ["thr_head", "0.10", "0.15", "0.20", "0.25"],
          [["Точность статуса", "0.884", "0.910", "0.910", "0.910"]])
    p(doc,
      "Порог 0.10 (каска должна лежать почти точно над точками лица) слишком строг: "
      "при виде сбоку или сверху каска смещена относительно носа и глаз, и надетая "
      "каска не засчитывается. Начиная с 0.15 результат стабилен — нормировка "
      "расстояния на высоту человека делает алгоритм нечувствительным к точному "
      "значению порога в широком диапазоне. Выбрано 0.15 как середина устойчивого "
      "участка.")

    h3(doc, "2.3. Пороги привязки к рукам и поясу и порог ключевых точек")
    table(doc,
          ["Параметр", "Значения", "Точность статуса"],
          [["thr_hand = thr_belt", "0.25 / 0.35 / 0.45", "0.910 / 0.910 / 0.910"],
           ["kp_conf", "0.3 / 0.5 / 0.7", "0.916 / 0.910 / 0.903"]])
    p(doc,
      "Пороги привязки к рукам и поясу в диапазоне 0.25–0.45 не влияют на результат: "
      "каска в руках или на поясе расположена заметно ближе к соответствующим точкам, "
      "чем к другим, поэтому выбор части тела устойчив. Порог уверенности ключевых "
      "точек влияет сильнее: слишком строгий (0.7) отбрасывает точки у рабочих спиной "
      "и в пол оборота, и их статус определяется хуже; мягкий порог 0.3 даёт лучший "
      "результат — при ошибочной точке максимум, что случится, — каска привяжется "
      "не туда, а пропуск точки почти всегда превращается в ошибку статуса.")

    h3(doc, "2.4. Резервная оценка головы по плечам (рабочие спиной)")
    p(doc,
      "В отчёте 2 этапа рабочие спиной к камере были названы главным ожидаемым "
      "источником ошибок: точки лица не видны, и надетая каска не может быть привязана "
      "к голове. Для этого случая реализована опция head_fallback: если видимых точек "
      "головы нет, её положение оценивается на 0.18 высоты человека выше середины линии "
      "плеч. Измерение на тестовом наборе:")
    table(doc,
          ["head_fallback", "Точность статуса", "Эффект"],
          [["выкл.", f"{0.9097:.3f}", "рабочий спиной в каске получает «без каски» или «не определён»"],
           ["вкл.", f"{s640['status_accuracy']:.3f}", "ложные тревоги для рабочих спиной устранены"]])
    p(doc,
      "На рисунке 1 показан характерный случай: спасатель спиной к камере в жёлтой "
      "каске. Без fallback система поднимала ложную тревогу «без каски», с fallback "
      "каска привязана к оценочному положению головы — статус «каска надета». "
      "Опция включена в итоговую конфигурацию.")
    picture(doc, ROOT / "runs" / "demo_fallback_extra_accident_01.png", 12,
            "Рис. 1. Рабочий спиной: с fallback каска распознана как надетая (зелёная рамка)")

    h2(doc, "3. Влияние размера входа детектора")
    p(doc,
      "Вторая гипотеза улучшения из отчёта 2 этапа — увеличение входа для мелких "
      "объектов: многие головы на общих планах занимают 15–25 пикселей. Модель "
      "YOLOv8n дообучена с размером входа 960×960 в тех же условиях (50 эпох).")
    pc640, pc960 = m640["per_class"], m960["per_class"]
    table(doc,
          ["Метрика (val)", "helmet 640", "helmet 960", "head 640", "head 960"],
          [["AP@0.5", f"{pc640['helmet']['AP50']:.3f}", f"{pc960['helmet']['AP50']:.3f}",
            f"{pc640['head']['AP50']:.3f}", f"{pc960['head']['AP50']:.3f}"],
           ["AP@0.5:0.95", f"{pc640['helmet']['AP50_95']:.3f}", f"{pc960['helmet']['AP50_95']:.3f}",
            f"{pc640['head']['AP50_95']:.3f}", f"{pc960['head']['AP50_95']:.3f}"],
           ["Recall", f"{pc640['helmet']['recall']:.3f}", f"{pc960['helmet']['recall']:.3f}",
            f"{pc640['head']['recall']:.3f}", f"{pc960['head']['recall']:.3f}"]])
    table(doc,
          ["Модель", "Точность статуса (testset)", "Полнота скрытых нарушений"],
          [["YOLOv8n, вход 640", f"{s640['status_accuracy']:.3f}", f"{s640['hidden_violation_recall']:.3f}"],
           ["YOLOv8n, вход 960", f"{s960['status_accuracy']:.3f}", f"{s960['hidden_violation_recall']:.3f}"]])
    p(doc,
      "На уровне детектора модели практически одинаковы: различия AP по классам helmet "
      "и head не превышают 0.003 — изображения датасета имеют исходное разрешение "
      "около 416×416, и апскейл до 960 не добавляет информации. На уровне задачи "
      "картина интереснее: модель 960 определила статусы чуть точнее (0.929 против "
      "0.916), но пропустила единственную в наборе каску в руках — полнота скрытых "
      "нарушений упала с 1.0 до 0.0, как у типового решения. Увеличение входа "
      "изменило уверенность детектора на нетипичном положении каски как раз в "
      "неудачную сторону. Поскольку выявление скрытых нарушений — главная цель "
      "проекта, в итоговую конфигурацию выбран вход 640: он быстрее, равен по "
      "качеству детекции и надёжнее на ключевом случае. Для камер с действительно "
      "высоким разрешением (4K) вход 960 стоит перепроверить на боевых записях.")

    h2(doc, "4. Итоговая конфигурация и направления улучшения")
    p(doc, "По результатам всех серий выбрана конфигурация:")
    bullets(doc, [
        "conf_det = 0.25 — сохраняет полноту скрытых нарушений;",
        "thr_head = 0.15, thr_hand = thr_belt = 0.35 — середина устойчивого диапазона;",
        "kp_conf = 0.3 — лучшая точность статуса;",
        "head_fallback включён — устраняет ложные тревоги для рабочих спиной;",
        "размер входа детектора 640 — оптимум качества и скорости для данного датасета.",
    ])
    p(doc,
      f"Итоговое качество на тестовом наборе: точность статуса {s640['status_accuracy']:.3f} "
      f"(было 0.910 в базовой конфигурации), полнота скрытых нарушений "
      f"{s640['hidden_violation_recall']:.3f}.")
    p(doc,
      "Оставшиеся ошибки и пути их устранения: ложные срабатывания на лицах с "
      "плакатов и баннеров (можно отфильтровывать статичные области кадра по "
      "нескольким секундам видео); пропуск сильно перекрытых людей в плотных группах "
      "(поможет модель оценки позы посильнее, например YOLOv8s-pose); пропуск касок, "
      "сливающихся с фоном (дообучение с аугментацией по цвету); каска в поднятой "
      "руке у головы как пограничный случай (на видео решается временной фильтрацией). "
      "Для промышленного применения стоит также дообучить детектор на записях с "
      "конкретных камер площадки.")

    h2(doc, "5. Выводы по этапу")
    p(doc,
      "Исследование показало, что качество системы определяется не столько точной "
      "настройкой порогов (алгоритм устойчив в широком диапазоне), сколько двумя "
      "содержательными решениями: умеренным порогом уверенности детектора, который "
      "сохраняет нетипичные положения каски, и резервной оценкой головы по плечам для "
      "рабочих спиной. Увеличение входа детектора для данного датасета эффекта не "
      "даёт. Итоговая система определяет статус рабочего с точностью 0.916, выявляет "
      "все скрытые нарушения тестового набора и работает в реальном времени, что "
      "подтверждает выполнение целей проекта.")

    out = ROOT.parent / "Отчёт_по_4_этапу_контроль_СИЗ_на_стройке.docx"
    doc.save(out)
    print("Сохранено:", out)


if __name__ == "__main__":
    main()
